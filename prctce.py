#LOOPS

##Range Function () - returns a series of numbers
#Range (based on the arguments(can be positive or negative)): 
# Start (optional; default value is 0)
# Stop (mandatory; stopping position, never included in the result of the range function)
# Step (specifies the increment value; default value is 1)
# EXAMPLE 1
for number in range (5):
    print (number)
print ()
# EXAMPLE 2
for number in range (1,6):
    print (number)
print ()
# EXAMPLE 3
for number in range (0,10,2):
    print (number)

## For Loop with Range (starting from 0 to stop - 1)
# Repeat a certain number of code for a certain number of time (based on the range function)
# The statement inside the for loop will be executed based on the sequence that is generated by the range function
# EXAMPLE 4 (outside the loop)
for number in range (5):
    print (number)
print ("Done") #str is outside the loop, meaning it will be printed once after the loop has finished all 5 repetitions
()
# EXAMPLE 5 (inside the loop)
for number in range (5):
    print (number)
    print ("Done") # str inside the loop, everytime the loop repeats, it prints the current number and the str 



